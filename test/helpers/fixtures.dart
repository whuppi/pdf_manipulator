  }
}

Future<Uint8List> buildFivePagePdf() async {
  final pdf = Pdf();
  try {
    final editor = await pdf.edit(src(minimalPdf));
    for (var i = 0; i < 4; i++) {
      await editor.mergeFrom(src(minimalPdf));
