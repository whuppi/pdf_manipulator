/// Register the native binary as a code asset.
/// Release/AOT routes through hook/link.dart (passthrough today —
/// see hook/link.dart for the tree-shaking roadmap).
void _registerCodeAsset(
  BuildInput input,
  BuildOutputBuilder output,
  File outFile,
  LinkMode linkMode,
) {
  output.assets.code.add(
    CodeAsset(
      package: input.packageName,
      name: _assetId,
      linkMode: linkMode,
      file: outFile.uri,
    ),
    routing: input.config.linkingEnabled
        ? ToLinkHook(input.packageName)
        : const ToAppBundle(),
  );
}

/// Register files Flutter should watch. Any change re-runs the hook;
/// cargo then decides what to actually recompile.
///
/// Must over-approximate cargo's inputs and must exist BEFORE the
/// first build — never derive this list from build outputs like
/// cargo dep-info, or caching goes circular and binaries go stale.
void _registerDependencies(BuildInput input, BuildOutputBuilder output) {
  output.dependencies.add(input.packageRoot.resolve('hook/build.dart'));
  output.dependencies.add(input.packageRoot.resolve('pubspec.yaml'));
  output.dependencies.add(input.packageRoot.resolve('build.json'));

  if (hasVendorSource(input.packageRoot)) {
    for (final crate in const ['vendor/pdf_oxide', 'vendor/office_oxide']) {
      _registerCrateSources(input, output, crate);
    }
  }
}

/// Register one vendored crate's buildable inputs: manifest, lock
/// file, build script, toolchain/flags config, and EVERY file under
/// src/ — not just .rs (include_bytes! assets are inputs too).
void _registerCrateSources(
  BuildInput input,
  BuildOutputBuilder output,
  String crate,
) {
  const configs = [
    'Cargo.toml',
    'Cargo.lock',
    'build.rs',
    'rust-toolchain.toml',
    'rust-toolchain',
    '.cargo/config.toml',
    '.cargo/config',
  ];
  for (final file in configs) {
    final uri = input.packageRoot.resolve('$crate/$file');
    if (File.fromUri(uri).existsSync()) {
      output.dependencies.add(uri);
    }
  }

  final srcDir = Directory.fromUri(input.packageRoot.resolve('$crate/src'));
  if (!srcDir.existsSync()) return;
  var registered = 0;
  for (final entry in srcDir.listSync(recursive: true)) {
    if (entry is File) {
      output.dependencies.add(entry.uri);
      registered++;
    }
  }
  _log.info('registered $registered source files from $crate/src');
}

