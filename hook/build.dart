// ══════════════════════════════════════════════════════════════════
// § 1 — Flutter hook entry point (native only)
//
// Called automatically for iOS, Android, macOS, Linux, Windows.
// NOT called for web — web goes through resolveWeb() via setup.dart.
// ══════════════════════════════════════════════════════════════════

void main(List<String> args) async {
  await build(args, (BuildInput input, BuildOutputBuilder output) async {
    if (!input.config.buildCodeAssets) return;

    final constants = BuildConstants.load(input.packageRoot);
    // The build-hook API exposes user-defines by key, not as a key set — so
    // build the map from the known keys and let the one parser validate it.
    // (Unknown-key rejection needs the full key set, which only the web path
    // has; native leans on the value-grammar + axis-mismatch checks.)
    final ud = input.userDefines;
    final cfg = PdfManipulatorConfig.parse({
      for (final k in PdfManipulatorConfig.knownKeys)
        if (ud[k] != null) k: ud[k],
    });
    final engineBuild = cfg.build;
    final plan = await resolveKeepPlan(
      keep: cfg.keep,
      detector: cfg.detector,
      defaultFeatures: constants.nativeFeatures,
      // NOT Directory.current: the runner starts every hook with its
      // working directory set to the package's OWN root, so reading it
      // scans pdf_manipulator, finds every capability where it is
      // implemented, and keeps all of them. The output directory is the
      // only handle on the consuming app a build hook is given.
      appRootCandidate: appRootFromHookOutput(input.outputDirectory),
      scanDirs: cfg.scanDirs,
    );
    if (plan.deferToLink && !input.config.linkingEnabled) {
      stderr.writeln(
        'pdf_manipulator detector record-use: linking is disabled in '
        'this build (debug) — shipping the FULL binary. Release builds '
        'trim in the link hook.',
      );
    }

    final codeConfig = input.config.code;
    final targetTriple = targetTripleFor(codeConfig);
    final linkMode = linkModeFor(codeConfig);
    final libFileName = codeConfig.targetOS.libraryFileName(
      constants.crate,
      linkMode,
    );
    final outFile = File.fromUri(input.outputDirectory.resolve(libFileName));

    // ── Resolve the binary (download, compile, or cache) ──
    await _resolveNative(
      constants: constants,
      plan: plan,
      engineBuild: engineBuild,
      packageRoot: input.packageRoot,
      version: readVersion(input.packageRoot),
      targetKey: targetKeyFor(codeConfig),
      libFileName: libFileName,
      dest: outFile,
      cacheFile: File.fromUri(
        input.outputDirectoryShared.resolve('$targetTriple/$libFileName'),
      ),
      targetTriple: targetTriple,
      linkMode: linkMode,
      buildInput: input,
    );

    // ── Register with Flutter ──
    _registerCodeAsset(input, output, outFile, linkMode);
    _registerDependencies(input, output);
    // The app source the keep decision was derived from. Without this the
    // runner caches the decision and never re-runs the hook, so an app that
    // starts calling a trimmed-away capability keeps building without it.
    output.dependencies.addAll(plan.appDependencies);
  });
}

// ══════════════════════════════════════════════════════════════════
// § 2 — Resolution
// ══════════════════════════════════════════════════════════════════

// ── Native (private) ─────────────────────────────────────────────
// Not public because the correct cache path, target triple, link
// mode, and NDK config all come from Flutter's BuildInput — which
// only exists inside the hook. Calling from outside writes to the
// wrong cache. setup --native delegates to `flutter build` instead.
Future<void> _resolveNative({
  required BuildConstants constants,
  required KeepPlan plan,
  required EngineBuild engineBuild,
  required Uri packageRoot,
  required String version,
  required String targetKey,
  required String libFileName,
  required File dest,
  required File cacheFile,
  required String targetTriple,
  required LinkMode linkMode,
  required BuildInput buildInput,
}) async {
  final assetName = '$targetKey-$libFileName';

  // Prebuilt release binaries exist ONLY for the default feature set on the
  // default (speed) build. A kept subset or a non-default build (size/debug)
  // has no prebuilt and no pinned hash: version 0.0.0 routes the resolver
  // straight to compile, and cargo's own fingerprint is the cache.
  final custom = plan.isCustom || !engineBuild.isDefault;
  final effectiveVersion = custom ? '0.0.0' : version;

  await resolveAsset(
    ResolveRequest(
      assetName: assetName,
      downloadUrl: constants.downloadUrl(effectiveVersion, assetName),
      dest: dest,
      cacheFile: custom ? null : cacheFile,
      expectedHash: custom ? null : assetHashes[assetName],
      version: effectiveVersion,
      packageRoot: packageRoot,
      compile: (File d) => _compileNativeFromHook(
        buildInput,
        targetTriple,
        linkMode,
        d,
        constants,
        plan,
        engineBuild,
      ),
    ),
  );
}

// ── Web (public — called by bin/setup.dart) ──────────────────────
// Resolves WASM + JS into destDir (typically web/pdf_manipulator/).
// Flutter serves destDir as static files — no registration needed.
//
// Two asset types with different compile fallbacks:
//   WASM build outputs (pdf_oxide_bg.wasm, pdf_oxide.js) → cargo + bindgen_runner
//   Hand-written JS (lane_worker.js) → copy from package
//
// Returns the number of files freshly resolved (0 = all cached).
Future<int> resolveWeb({
  required Uri packageRoot,
  required String version,
  required Directory destDir,
  bool force = false,
  String? wasmFeaturesOverride,
  EngineBuild engineBuild = EngineBuild.speed,
}) async {
  final constants = BuildConstants.load(packageRoot);
  // A kept subset OR a non-default build has no prebuilt asset, no pinned
  // hash, and must not reuse a default-set artifact: force + version 0.0.0
  // route the resolver straight to a fresh compile.
  final custom = wasmFeaturesOverride != null || !engineBuild.isDefault;
  final effectiveVersion = custom ? '0.0.0' : version;
  final effectiveForce = force || custom;

  if (!destDir.existsSync()) {
    destDir.createSync(recursive: true);
  }

  var installed = 0;

  for (final entry in constants.webAssets.entries) {
    final localName = entry.key;
    final assetName = entry.value;
    final dest = File('${destDir.path}/$localName');

    final isWasmBuildOutput = constants.wasmBuildOutputs.contains(localName);

    final fresh = await resolveAsset(
      ResolveRequest(
        assetName: assetName,
        downloadUrl: constants.downloadUrl(effectiveVersion, assetName),
        dest: dest,
        expectedHash: custom ? null : assetHashes[assetName],
        version: effectiveVersion,
        packageRoot: packageRoot,
        force: effectiveForce,
        compile: isWasmBuildOutput
            ? (File d) => _compileWasm(
                packageRoot,
                d,
                localName,
                wasmFeaturesOverride,
                engineBuild,
              )
            : (File d) => _copyWebAsset(packageRoot, d, localName),
      ),
    );

    if (fresh) installed++;
  }

  return installed;
}

