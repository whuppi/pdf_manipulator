// ── Native: from build hook (has BuildInput with NDK, triple) ────

Future<void> _compileNativeFromHook(
  BuildInput input,
  String targetTriple,
  LinkMode linkMode,
  File outFile,
) async {
  final manifestPath = p.fromUri(
    input.packageRoot.resolve('vendor/pdf_oxide/Cargo.toml'),
  );
  final targetDir =
      p.join(p.fromUri(input.outputDirectory), 'cargo_target');

  _log.info('compiling from source for $targetTriple');

  // Ensure the Rust target is installed (fresh CI or formatted laptop)
  final targetCheck = Process.runSync(
    'rustup', ['target', 'list', '--installed'],
  );
  if (targetCheck.exitCode == 0 &&
      !(targetCheck.stdout as String).contains(targetTriple)) {
    _log.info('installing Rust target: $targetTriple');
    Process.runSync('rustup', ['target', 'add', targetTriple]);
  }

  final env = <String, String>{};
  final codeConfig = input.config.code;

  // Android: use the NDK clang driver Flutter provides
  if (codeConfig.targetOS == OS.android) {
    final cc = codeConfig.cCompiler;
    if (cc != null) {
      final compilerDir = p.dirname(p.fromUri(cc.compiler));
      final ndkTriple = targetTriple == 'armv7-linux-androideabi'
          ? 'armv7a-linux-androideabi'
          : targetTriple;
      // The NDK per-API clang driver is a `.cmd` batch wrapper on Windows
      // hosts (e.g. aarch64-linux-android21-clang.cmd); passing the bare name
      // makes cargo fail with "could not exec the linker ... program not
      // found". Append the host executable extension so Android cross-compiles
      // link from a Windows host as well as Linux/macOS. Platform.isWindows
      // here is the BUILD host (which runs cargo), not the Android target.
      final clangExt = Platform.isWindows ? '.cmd' : '';
      final linker = p.join(compilerDir, '${ndkTriple}21-clang$clangExt');
      final ar = p.join(compilerDir, 'llvm-ar');
      final envKey =
          'CARGO_TARGET_${targetTriple.toUpperCase().replaceAll('-', '_')}';
      env['${envKey}_LINKER'] = linker;
      env['${envKey}_AR'] = ar;
      _log.info('NDK linker: $linker');
    }
  }

  // macOS: strip Xcode Developer PATH injections that break cargo
  if (Platform.isMacOS) {
    env['PATH'] = Platform.environment['PATH']!
        .split(':')
        .where((e) => !e.contains('Contents/Developer/'))
        .join(':');
  }

  // hooks_runner strips SCCACHE_* and ACTIONS_* env vars (dart-lang/native
  // allowlist). sccache is on PATH but without SCCACHE_GHA_ENABLED and
  // ACTIONS_CACHE_URL it falls back to local disk (useless on fresh CI).
  //
  // The rust CI capability writes /tmp/sccache-wrapper.sh that re-injects
  // the stripped vars before calling sccache. Prefer it over raw sccache.
  // On local dev or when the wrapper doesn't exist, fall back to raw sccache.
  final wrapperPath = '/tmp/sccache-wrapper.sh';
  final wrapper = File(wrapperPath);
  if (wrapper.existsSync()) {
    env['RUSTC_WRAPPER'] = wrapperPath;
    _log.info('sccache enabled via wrapper (GHA cache)');
  } else {
    final sccache = _findOnPath('sccache');
    if (sccache != null) {
      env['RUSTC_WRAPPER'] = sccache;
      _log.info('sccache enabled: $sccache (local cache only)');
    }
  }

  final result = await Process.run(
    'cargo',
    [
      'build',
      '--manifest-path', manifestPath,
      '--lib',
      '--release',
      '--target', targetTriple,
      '--target-dir', targetDir,
      '--features', _resolveFeatures(),
    ],
    environment: {...Platform.environment, ...env},
  );

  if (result.exitCode != 0) {
    throw StateError(
      'cargo build failed (exit ${result.exitCode}).\n'
      'stderr: ${result.stderr}\n\n'
      'Ensure Rust is installed: https://rustup.rs\n'
      'Then: rustup target add $targetTriple',
    );
  }

  final compiled = p.join(
    targetDir,
    targetTriple,
    'release',
    codeConfig.targetOS
        .libraryFileName(_crateName, linkMode)
        .replaceAll('-', '_'),
  );

  if (!File(compiled).existsSync()) {
    throw StateError('Compiled library not found at $compiled.');
  }

  outFile.parent.createSync(recursive: true);
  File(compiled).copySync(outFile.path);
  _log.info('compiled → ${outFile.path}');
}

// ── Native: from CLI (no BuildInput — uses compile_rust.sh) ──────

Future<void> _compileNativeFromCli(Uri packageRoot, File dest) async {
  final script =
      File.fromUri(packageRoot.resolve('tool/compile_rust.sh'));
  if (!script.existsSync()) {
    throw StateError(
      'tool/compile_rust.sh not found. Cannot compile from source.\n'
      'Install from pub.dev or use a git tag with pre-built binaries.',
    );
  }

  final result = await Process.run(
    'bash',
    [script.path, '--native'],
    workingDirectory: p.fromUri(packageRoot),
  );
  if (result.exitCode != 0) {
    throw StateError(
      'Native compilation failed (exit ${result.exitCode}).\n'
      'stderr: ${result.stderr}\n\n'
      'Ensure Rust is installed: https://rustup.rs',
    );
  }

  final libFileName = _currentLibFileName();
  final compiled = File(p.join(
    p.fromUri(packageRoot),
    'vendor/pdf_oxide/target/release',
    libFileName,
  ));
  if (!compiled.existsSync()) {
    throw StateError('Compiled binary not found at ${compiled.path}');
  }
  dest.parent.createSync(recursive: true);
  compiled.copySync(dest.path);
}

// ── Web: WASM build outputs (pdf_oxide.js + pdf_oxide_bg.wasm) ───

Future<void> _compileWasm(
    Uri packageRoot, File dest, String targetFile) async {
  final existing =
      File.fromUri(packageRoot.resolve('web_assets/$targetFile'));

  // Contributor has locally built WASM — copy directly
  if (existing.existsSync()) {
    dest.parent.createSync(recursive: true);
    existing.copySync(dest.path);
    return;
  }

  // Compile from source
  final script =
      File.fromUri(packageRoot.resolve('tool/compile_rust.sh'));
  if (!script.existsSync()) {
    throw StateError(
      'tool/compile_rust.sh not found. Cannot compile WASM.\n'
      'Install from pub.dev or use a git tag with pre-built binaries.',
    );
  }

  final result = await Process.run(
    'bash',
    [script.path, '--wasm'],
    workingDirectory: p.fromUri(packageRoot),
  );
  if (result.exitCode != 0) {
    throw StateError(
      'WASM compilation failed (exit ${result.exitCode}).\n'
      'stderr: ${result.stderr}\n\n'
      'Ensure Rust + wasm-pack are installed:\n'
      '  https://rustup.rs\n'
      '  cargo install wasm-pack',
    );
  }

  if (!existing.existsSync()) {
    throw StateError(
        'WASM compiled but $targetFile not found at ${existing.path}');
  }
  dest.parent.createSync(recursive: true);
  existing.copySync(dest.path);
}

// ── Web: hand-written JS (coordinator.js, worker.js) ─────────────

Future<void> _copyWebAsset(
    Uri packageRoot, File dest, String fileName) async {
  final src = File.fromUri(packageRoot.resolve('web_assets/$fileName'));
  if (!src.existsSync()) {
    throw StateError('$fileName not found in web_assets/');
  }
  dest.parent.createSync(recursive: true);
  src.copySync(dest.path);
}

